import { readFile, writeFile } from 'node:fs/promises';

const config = JSON.parse(await readFile('assets/data/portfolio.json', 'utf8'));
const ids = (config.universeIds || []).map(Number).filter(Number.isSafeInteger);
if (!ids.length) throw new Error('assets/data/portfolio.json has no valid Universe IDs.');

const response = await fetch(`https://games.roblox.com/v1/games?universeIds=${encodeURIComponent(ids.join(','))}`, { headers: { Accept: 'application/json' } });
if (!response.ok) throw new Error(`Roblox returned ${response.status}`);
const payload = await response.json();
const thumbnailResponse = await fetch(`https://thumbnails.roblox.com/v1/games/icons?universeIds=${encodeURIComponent(ids.join(','))}&size=512x512&format=Png&isCircular=false`, { headers: { Accept: 'application/json' } });
if (!thumbnailResponse.ok) throw new Error(`Roblox thumbnails returned ${thumbnailResponse.status}`);
const thumbnailPayload = await thumbnailResponse.json();
const thumbnails = new Map((thumbnailPayload.data || []).map(image => [image.targetId, image.imageUrl]));
const labels = new Map(Object.entries(config.labels || {}).map(([id, label]) => [Number(id), String(label || 'Portfolio')]));
const games = (payload.data || []).map(game => ({
  id: game.id, rootPlaceId: game.rootPlaceId, name: game.name, description: game.description,
  visits: game.visits, playing: game.playing, thumbnailUrl: thumbnails.get(game.id) || null,
  label: labels.get(game.id) || 'Portfolio'
}));
const snapshot = { updatedAt: new Date().toISOString(), games };
await writeFile('assets/data/portfolio-live.json', `${JSON.stringify(snapshot, null, 2)}\n`);
await writeFile('assets/js/portfolio-data.js', `/* Generated by scripts/refresh-portfolio.mjs — do not hand-edit live figures. */\nwindow.PORTFOLIO_SNAPSHOT = ${JSON.stringify(snapshot, null, 2)};\n`);
